// App feedback goes to a "feedback inbox" pull request in the app's GitHub repo.
// The Claude Code session that builds Wander is subscribed to it, picks feedback
// up, builds a new version, and replies there; the app shows those replies.

import { load, save } from './store.ts';

declare const __APP_VERSION__: string;

const REPO = 'agrawalprash/mysteryjunction';
const INBOX_BRANCH = 'claude/feedback-inbox';
const API = 'https://api.github.com';

export interface ThreadComment {
  author: string;
  body: string;
  at: string;
  fromClaude: boolean;
}

/** Number of the open inbox pull request, or null if it isn't set up yet. */
export async function findInbox(force = false): Promise<number | null> {
  const cached = load<{ at: number; n: number | null } | null>('feedback-inbox', null);
  if (!force && cached && cached.n && Date.now() - cached.at < 24 * 60 * 60 * 1000) return cached.n;
  const owner = REPO.split('/')[0];
  const res = await fetch(`${API}/repos/${REPO}/pulls?state=open&head=${owner}:${INBOX_BRANCH}`, { headers: { Accept: 'application/vnd.github+json' } });
  if (!res.ok) throw new Error(`Couldn’t reach GitHub (${res.status}).`);
  const prs = await res.json();
  const n = prs[0]?.number ?? null;
  save('feedback-inbox', { at: Date.now(), n });
  return n;
}

/** Facts that help reproduce a problem; added under the message. */
export function context(device: 'phone' | 'TV'): string {
  return [
    `Wander ${__APP_VERSION__} on the ${device}`,
    `screen ${window.innerWidth}×${window.innerHeight} @${window.devicePixelRatio}x`,
    `${navigator.userAgent.match(/Android [\d.]+/)?.[0] ?? 'unknown Android'}`,
  ].join(' · ');
}

export async function postFeedback(token: string, text: string, device: 'phone' | 'TV'): Promise<void> {
  const n = await findInbox();
  if (!n) throw new Error('The feedback inbox isn’t set up yet. Ask Claude in your Claude Code session to create it.');
  const body = `**Feedback from the Wander app**\n\n${text
    .split('\n')
    .map((l) => `> ${l}`)
    .join('\n')}\n\n<sub>${context(device)}</sub>`;
  const res = await fetch(`${API}/repos/${REPO}/issues/${n}/comments`, {
    method: 'POST',
    headers: { Accept: 'application/vnd.github+json', Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ body }),
  });
  if (res.status === 401 || res.status === 403) throw new Error('GitHub refused the token. Check it can write to Issues and Pull requests for this repository.');
  if (!res.ok) throw new Error(`GitHub said ${res.status} when posting.`);
}

/** The latest messages in the inbox (feedback and Claude's replies). */
export async function thread(limit = 8): Promise<ThreadComment[]> {
  const n = await findInbox();
  if (!n) return [];
  const res = await fetch(`${API}/repos/${REPO}/issues/${n}/comments?per_page=100`, { headers: { Accept: 'application/vnd.github+json' } });
  if (!res.ok) return [];
  const all = (await res.json()) as { user?: { login?: string }; body?: string; created_at?: string }[];
  return all.slice(-limit).map((c) => {
    const body = String(c.body ?? '');
    const fromClaude = /Generated by \[Claude Code\]/.test(body);
    return {
      author: c.user?.login ?? '',
      at: c.created_at ?? '',
      fromClaude,
      body: body
        .replace(/\n---\n_Generated by \[Claude Code\]\([^)]*\)_\s*$/, '')
        .replace(/<sub>[\s\S]*?<\/sub>/g, '')
        .replace(/^\*\*Feedback from the Wander app\*\*\s*/, '')
        .replace(/^> ?/gm, '')
        .trim(),
    };
  });
}
